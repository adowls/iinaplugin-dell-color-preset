#!/usr/bin/env python3
"""Turn the built helper and profile JSON into CommonJS resources for IINA."""

import json
import pathlib
import sys


def main() -> None:
    helper_path, profiles_path, output_dir = map(pathlib.Path, sys.argv[1:4])
    output_dir.mkdir(parents=True, exist_ok=True)

    helper_bytes = helper_path.read_bytes()
    chunk_size = 4096
    chunks = [helper_bytes[i : i + chunk_size]
              for i in range(0, len(helper_bytes), chunk_size)]
    chunk_expressions = [
        "new Uint8Array([" + ",".join(str(byte) for byte in chunk) + "])"
        for chunk in chunks
    ]
    (output_dir / "helperPayload.js").write_text(
        "// Generated by native/scripts/embed_plugin_resources.py.\n"
        "// Split into small arrays to keep JavaScriptCore parsing reliable.\n"
        "module.exports = [\n  " + ",\n  ".join(chunk_expressions) + "\n];\n",
        encoding="utf-8",
    )

    profiles = json.loads(profiles_path.read_text(encoding="utf-8"))
    (output_dir / "profilesPayload.js").write_text(
        "// Generated by native/scripts/embed_plugin_resources.py.\n"
        "module.exports = " + json.dumps(profiles, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
